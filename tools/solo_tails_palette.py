"""Protect solo Tails' fur from shared enemy colours.
Run after import_tails_poses.py; --check verifies all generated resources.
"""
import argparse,re
from pathlib import Path
from nemesis import decode
ROOT=Path(__file__).resolve().parents[1]
# Source 14/15/11 -> Sonic's bright/middle/dark fur slots (also used by a few objects).
COLOURS=tuple({14:2,15:3,11:4}.get(i,i) for i in range(16))

def remap_fur(data):
    return bytes((COLOURS[b >> 4] << 4) | COLOURS[b & 15] for b in data)

def generate():
    data=(ROOT/"art/uncompressed/Tails's art.bin").read_bytes()+(ROOT/'art/uncompressed/Tails poses.bin').read_bytes()
    outputs={ROOT/'art/uncompressed/Tails solo protected.bin':remap_fur(data)}
    # The 2x2 portrait is shared by Tails and Miles. Leave the name and life
    # digits in VRAM untouched by uploading only the four portrait tiles.
    icon = decode((ROOT / 'art/nemesis/Tails life counter.nem').read_bytes())[:4*32]
    miles_icon = decode((ROOT / 'art/nemesis/Miles life counter.nem').read_bytes())[:4*32]
    assert len(icon) == 4*32 and icon == miles_icon
    outputs[ROOT / 'art/uncompressed/Tails solo life portraits.bin'] = icon + remap_fur(icon)
    text='\n'.join((ROOT/p).read_text() for p in ['mappings/spriteDPLC/Tails.asm','mappings/spriteDPLC/Tails poses.asm'])
    labels=re.findall(r'mappingsTableEntry.w\s+(\w+)',text)
    lines=['; Generated by tools/solo_tails_palette.py. Same VRAM order as Tails.',
           '; Split a DMA task if this art copy straddles a 128 KiB source bank.',
           'soloTailsDplcEntry macro count,first',
           '\tif (((ArtUnc_SoloTails+(first)*32)&$1FFFF)+(count)*32)>$20000',
           '\t\tdplcEntry ($20000-((ArtUnc_SoloTails+(first)*32)&$1FFFF))/32, first',
           '\t\tdplcEntry (count)-($20000-((ArtUnc_SoloTails+(first)*32)&$1FFFF))/32, (first)+($20000-((ArtUnc_SoloTails+(first)*32)&$1FFFF))/32',
           '\telse', '\t\tdplcEntry count,first', '\tendif', '\tendm',
           'MapRUnc_SoloTails: mappingsTable']
    for i in range(len(labels)):lines.append(f'\tmappingsTableEntry.w SoloTailsPLC_{i:02X}')
    for i,label in enumerate(labels):
        record=re.search(r'^'+re.escape(label)+r':(.*?)(?=^'+re.escape(label)+r'_End)',text,re.M|re.S)[1]
        lines.append(f'SoloTailsPLC_{i:02X}: dplcHeader')
        for count,start in re.findall(r'dplcEntry\s+([^,\n]+),([^;\n]+)',record):lines.append(f'\tsoloTailsDplcEntry {count.strip()}, {start.strip()}')
        lines.append(f'SoloTailsPLC_{i:02X}_End')
    lines+=['\teven','']
    outputs[ROOT/'mappings/spriteDPLC/Tails solo protected.asm']='\n'.join(lines).encode()
    # Sonic's pilot mapping draws the first six tiles of these four frames.
    sonic=(ROOT/"art/uncompressed/Sonic's art.bin").read_bytes()+(ROOT/'art/uncompressed/Sonic victory.bin').read_bytes()
    source=(ROOT/'mappings/spriteDPLC/Sonic.asm').read_text()
    names=re.findall(r'mappingsTableEntry.w\s+([.\w]+)',source)
    pilot=bytearray();plc=['MapRUnc_SoloSonicPilot: mappingsTable']
    for i in range(4):plc.append(f'\tmappingsTableEntry.w SoloPilotPLC_{i}')
    for i in range(4):
        label=names[0x2d+i];record=re.search(r'^'+re.escape(label)+r':(.*?)(?=^'+re.escape(label)+r'_End)',source,re.M|re.S)[1];frame=b''
        for count,start in re.findall(r'dplcEntry\s+([^,\n]+),([^;\n]+)',record):
            count,start=[int(v.strip().replace('$','0x'),0) for v in [count,start]]
            frame+=sonic[start*32:(start+count)*32]
        frame=frame[:6*32];assert len(frame)==192
        for lookup in [tuple(0 if c in [2,3,4] else c for c in range(16)),tuple({2:14,3:15}.get(c,0) for c in range(16)),tuple(15 if c==4 else 0 for c in range(16))]:
            pilot.extend((lookup[v>>4]<<4)|lookup[v&15] for v in frame)
        plc += [f'SoloPilotPLC_{i}: dplcHeader',f'\tdplcEntry 16, {i*18}',f'\tdplcEntry 2, {i*18+16}',f'SoloPilotPLC_{i}_End']
    plc+=['\teven','']
    outputs[ROOT/'art/uncompressed/Sonic pilot protected.bin']=bytes(pilot)
    outputs[ROOT/'mappings/spriteDPLC/Sonic pilot protected.asm']='\n'.join(plc).encode()
    maps=(ROOT/'mappings/sprite/objB2_a.asm').read_text().replace('Map_objB2_a','Map_SoloSonicPilot')
    old='\tspritePiece\t-$32, -8, 3, 2, $280, 0, 0, 0, 0'
    new=old+'\n\tspritePiece\t-$32, -8, 3, 2, $286, 0, 0, 2, 0\n\tspritePiece\t-$32, -8, 3, 2, $28C, 0, 0, 3, 0'
    assert maps.count(old)==4
    outputs[ROOT/'mappings/sprite/Sonic pilot protected.asm']=maps.replace(old,new).encode()
    return outputs

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
    stale=[(p,d) for p,d in generate().items() if not p.exists() or p.read_bytes()!=d]
    if args.check:
        print('up to date' if not stale else 'stale: '+', '.join(str(p) for p,d in stale));raise SystemExit(bool(stale))
    for p,data in stale:p.write_bytes(data);print('wrote',p.relative_to(ROOT))

if __name__=='__main__':main()

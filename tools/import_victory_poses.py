"""Generate Sonic's victory pose (FeatureVictoryPoses) from the s1_improvements source bundle.

Usage: python tools/import_victory_poses.py [--bundle PATH_TO/source_inputs.zip] [--check]

The pose is AleDrawer2008's two-finger victory pose from "Add Victory Poses In
Sonic 1" (cd/Victory Sprites.png in s1_improvements' tools/data/source_inputs.zip),
the same source s1_improvements imports. The sheet has two 32x40 cells; each
frame is aligned on its own left edge with the feet on the standing baseline.
Its colours are Sonic's palette entries 1-13, which Sonic 2 keeps at the same
indices; the darkest shoe red has no Sonic 2 slot and becomes index 13.

Writes art/uncompressed/Sonic victory.bin (appended to Sonic's art in the ROM),
mappings/sprite/Sonic victory.asm and mappings/spriteDPLC/Sonic victory.asm.
"""
import argparse, hashlib, io, zipfile
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_BUNDLE = ROOT.parent / 's1_improvements' / 'tools' / 'data' / 'source_inputs.zip'
SHEET = 'cd/Victory Sprites.png'
SHEET_SHA256 = '2f54ad0155c0ba0b3874fb7da702bef586629f030ef25ab53c2c2b820e290d9d'
COLOURS = [  # index -> RGB of the sheet, as in s1_improvements (index 0 unused)
    (153, 217, 234), (0, 0, 0), (32, 36, 144), (72, 72, 176), (104, 108, 216),
    (144, 144, 248), (248, 252, 248), (176, 180, 176), (144, 144, 144), (72, 72, 72),
    (248, 180, 144), (176, 108, 72), (248, 0, 0), (144, 0, 0), (72, 0, 0),
]
TO_S2 = {14: 13}  # darkest shoe red -> Sonic 2's dark red


def frames_from_sheet(raw):
    im = Image.open(io.BytesIO(raw)).convert('RGBA')
    frames = []
    for cell in range(2):
        solid = {}
        for y in range(40):
            for x in range(32):
                c = im.getpixel((cell * 32 + x, y))
                if c[3]:
                    solid[x, y] = c[:3]
        left = min(x for x, _ in solid)
        pix = {}
        for (x, y), c in solid.items():
            dist, idx = min((sum((a - b) ** 2 for a, b in zip(rgb, c)), i)
                            for i, rgb in enumerate(COLOURS) if i)
            assert dist <= 3 * 8 ** 2, c
            pix[x - left - 12, y - 20] = TO_S2.get(idx, idx)
        frames.append(pix)
    return frames


def pack(pix):
    """Cover the frame with pieces of up to 4x4 tiles; returns (art, pieces)."""
    x0 = min(x for x, _ in pix) // 8 * 8
    y0 = min(y for _, y in pix) // 8 * 8
    x1 = max(x for x, _ in pix) + 1
    y1 = max(y for _, y in pix) + 1
    art = bytearray()
    pieces = []
    for py in range(y0, y1, 32):
        for px in range(x0, x1, 32):
            w = min(4, (x1 - px + 7) // 8)
            h = min(4, (y1 - py + 7) // 8)
            if not any((x, y) in pix for x in range(px, px + w * 8) for y in range(py, py + h * 8)):
                continue
            first = len(art) // 32
            for tx in range(w):          # tiles go column by column
                for ty in range(h):
                    for row in range(8):
                        v = 0
                        for col in range(8):
                            v = (v << 4) | pix.get((px + tx * 8 + col, py + ty * 8 + row), 0)
                        art += v.to_bytes(4, 'big')
            pieces.append((px, py, w, h, first))
    return bytes(art), pieces


def generate(bundle):
    raw = zipfile.ZipFile(bundle).read(SHEET)
    assert hashlib.sha256(raw).hexdigest() == SHEET_SHA256, 'unexpected victory sheet'
    base = (ROOT / 'art' / 'uncompressed' / "Sonic's art.bin").stat().st_size // 32
    art = bytearray()
    maps = ['; Sonic\'s victory pose (FeatureVictoryPoses), generated by tools/import_victory_poses.py']
    dplc = list(maps)
    for i, pix in enumerate(frames_from_sheet(raw)):
        a, pieces = pack(pix)
        name = f'Map_Sonic_Victory{i}'
        maps.append(f'{name}:\tspriteHeader')
        for x, y, w, h, t in pieces:
            maps.append(f'\tspritePiece\t{x}, {y}, {w}, {h}, ${t:X}, 0, 0, 0, 0')
        maps += [f'{name}_End', '']
        dname = f'DPLC_Sonic_Victory{i}'
        dplc.append(f'{dname}:\tdplcHeader')
        tile, count = base + len(art) // 32, len(a) // 32
        while count:
            n = min(count, 16)
            dplc.append(f'\tdplcEntry\t{n}, ${tile:X}')
            tile += n
            count -= n
        dplc += [f'{dname}_End', '']
        art += a
    return {
        ROOT / 'art' / 'uncompressed' / 'Sonic victory.bin': bytes(art),
        ROOT / 'mappings' / 'sprite' / 'Sonic victory.asm': ('\n'.join(maps) + '\n\teven\n').encode(),
        ROOT / 'mappings' / 'spriteDPLC' / 'Sonic victory.asm': ('\n'.join(dplc) + '\n\teven\n').encode(),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--bundle', type=Path, default=DEFAULT_BUNDLE)
    ap.add_argument('--check', action='store_true', help='only verify the files are up to date')
    args = ap.parse_args()
    outputs = generate(args.bundle)
    stale = [p for p, data in outputs.items() if not p.exists() or p.read_bytes() != data]
    if args.check:
        print('up to date' if not stale else 'stale: ' + ', '.join(str(p.relative_to(ROOT)) for p in stale))
        raise SystemExit(1 if stale else 0)
    for p, data in outputs.items():
        p.write_bytes(data)
        print('wrote', p.relative_to(ROOT))


if __name__ == '__main__':
    main()

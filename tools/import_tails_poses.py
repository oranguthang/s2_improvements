"""Import Tails' victory and Super transformation poses from Sonic 3 & Knuckles.

Usage: python tools/import_tails_poses.py [--bundle PATH_TO/source_inputs.zip] [--check]

Reads the S3K Tails sprites in s1_improvements' source bundle
(sk/General/Sprites/Tails: art, mappings, DPLC; s1_improvements imports the
same frames): AniTails13's thumbs-up and kneel ($A5, $A6) for the victory pose
and AniTails29's transformation ($EB-$ED). S3K reads body frames from $D1 on
from a separate extra sheet. Colours are remapped by meaning to the Sonic 2
player palette (Tails' fur is 14/15/11 there).

Writes art/uncompressed/Tails poses.bin (appended to Tails' art in the ROM),
mappings/sprite/Tails poses.asm and mappings/spriteDPLC/Tails poses.asm, frames
$9C-$A0 in Tails' tables.
"""
import argparse, re, zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_BUNDLE = ROOT.parent / 's1_improvements' / 'tools' / 'data' / 'source_inputs.zip'
BASE = 'sk/General/Sprites/Tails/'
EXTRA_FIRST = 0xD1
FRAMES = [(0xA5, 'Victory0'), (0xA6, 'Victory1'), (0xEB, 'Transform0'), (0xEC, 'Transform1'), (0xED, 'Transform2')]
FIRST_S2_FRAME = 0x9C
# S3K Tails palette index -> Sonic 2 player palette index
COLOURS = (0, 6, 14, 15, 11, 9, 12, 13, 14, 15, 10, 11, 7, 8, 9, 1)


def parse_table(text):
    lines = text.splitlines()
    names = [m[1] for l in lines if (m := re.search(r'dc\.w\s+(\w+)-\w+_\s*;', l))]
    bodies, cur = {}, None
    for l in lines:
        m = re.match(r'(\w+):\s*dc\.w\s+(\S+)', l)
        if m:
            cur = m[1]
            bodies[cur] = [int(m[2].replace('$', '0x'), 0)]
            continue
        if cur and re.search(r'\bdc\.[bw]\b', l):
            kind = 'b' if 'dc.b' in l else 'w'
            vals = [int(v.strip().replace('$', '0x'), 0) for v in l.split('dc.' + kind, 1)[1].split(';')[0].split(',')]
            bodies[cur].append((kind, vals))
    return names, bodies


def flat_bytes(body):
    out = []
    for kind, vals in body[1:]:
        for v in vals:
            out += [v & 0xFF] if kind == 'b' else [(v >> 8) & 0xFF, v & 0xFF]
    return out


def s8(v):
    return v - 256 if v & 0x80 else v


def s16(v):
    return v - 65536 if v & 0x8000 else v


def generate(bundle):
    z = zipfile.ZipFile(bundle)
    body_art = z.read(BASE + 'Art/Tails.bin')
    extra_art = z.read(BASE + 'Art/Tails Extra.bin')
    map_names, maps = parse_table(z.read(BASE + 'Map - Tails.asm').decode('latin1'))
    plc_names, plcs = parse_table(z.read(BASE + 'DPLC - Tails.asm').decode('latin1'))
    base = (ROOT / 'art' / 'uncompressed' / "Tails's art.bin").stat().st_size // 32
    art = bytearray()
    out_map = ['; Tails\' victory and transformation poses from Sonic 3 & Knuckles, generated by tools/import_tails_poses.py']
    out_plc = list(out_map)
    for n, (frame, label) in enumerate(FRAMES):
        sheet = extra_art if frame >= EXTRA_FIRST else body_art
        plc = plcs[plc_names[frame]]
        words = []
        for kind, vals in plc[1:]:
            words += vals
        assert len(words) == plc[0]
        tiles = bytearray()
        for w in words:
            count, offset = (w >> 12) + 1, w & 0xFFF
            tiles += sheet[offset * 32:(offset + count) * 32]
        tiles = bytes((COLOURS[b >> 4] << 4) | COLOURS[b & 15] for b in tiles)
        name = f'Map_Tails_{label}'
        out_map.append(f'{name}:\tspriteHeader\t; ${FIRST_S2_FRAME + n:X} (S3K ${frame:X})')
        raw = flat_bytes(maps[map_names[frame]])
        assert len(raw) == 6 * maps[map_names[frame]][0]
        for i in range(0, len(raw), 6):
            y, size, tile, x = s8(raw[i]), raw[i + 1], (raw[i + 2] << 8) | raw[i + 3], s16((raw[i + 4] << 8) | raw[i + 5])
            w, h = ((size >> 2) & 3) + 1, (size & 3) + 1
            assert tile & 0xE000 == 0, 'unexpected priority/palette bits'
            out_map.append(f'\tspritePiece\t{x}, {y}, {w}, {h}, ${tile & 0x7FF:X}, {(tile >> 11) & 1}, {(tile >> 12) & 1}, 0, 0')
        out_map += [f'{name}_End', '']
        dname = f'DPLC_Tails_{label}'
        out_plc.append(f'{dname}:\tdplcHeader')
        tile, count = base + len(art) // 32, len(tiles) // 32
        while count:
            k = min(count, 16)
            out_plc.append(f'\tdplcEntry\t{k}, ${tile:X}')
            tile += k
            count -= k
        out_plc += [f'{dname}_End', '']
        art += tiles
    return {
        ROOT / 'art' / 'uncompressed' / 'Tails poses.bin': bytes(art),
        ROOT / 'mappings' / 'sprite' / 'Tails poses.asm': ('\n'.join(out_map) + '\n\teven\n').encode(),
        ROOT / 'mappings' / 'spriteDPLC' / 'Tails poses.asm': ('\n'.join(out_plc) + '\n\teven\n').encode(),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--bundle', type=Path, default=DEFAULT_BUNDLE)
    ap.add_argument('--check', action='store_true', help='only verify the files are up to date')
    args = ap.parse_args()
    outputs = generate(args.bundle)
    stale = [p for p, data in outputs.items() if not p.exists() or p.read_bytes() != data]
    if args.check:
        print('up to date' if not stale else 'stale: ' + ', '.join(str(p.relative_to(ROOT)) for p in stale))
        raise SystemExit(1 if stale else 0)
    for p, data in outputs.items():
        p.write_bytes(data)
        print('wrote', p.relative_to(ROOT))


if __name__ == '__main__':
    main()
